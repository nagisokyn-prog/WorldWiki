use crate::rules::{Category, RuleDefinition, Severity};

#[inline]
fn r(id: &str, cat: Category, sev: Severity, title: &str, desc: &str, rem: &str) -> RuleDefinition {
    RuleDefinition {
        id: id.into(),
        version: "1.0".into(),
        category: cat,
        severity: sev,
        title: title.into(),
        description: desc.into(),
        remediation: rem.into(),
    }
}

