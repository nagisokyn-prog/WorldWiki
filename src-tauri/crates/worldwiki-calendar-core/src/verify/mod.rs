//! Модуль формальной верификации математических инвариантов Kani Model Checker.
//!
//! Доказательства разделены по независимым математическим доменам:
//! - verify_scalar: Евклидова арифметика, неделимость и обратимость t_abs <-> LocalMoment
//! - verify_leap: Ограниченность шага високоса {0, 1}, монотонность и отсутствие переполнений i128
//! - verify_year: Сходимость O(1) поиска года ровно за 0..2 итерации цикла
//! - verify_dial: Симметричное квантование циферблатов ceil/floor без потери квантов
//! - verify_eras: Полнота бинарного поиска эр и корректность високосных годовщин
//! - verify_age: Монотонность возраста и корректность переноса високосных дней рождения
//! - verify_intervals: Полнота алгебры Аллена, обнаружение билокации и посмертных сцен

